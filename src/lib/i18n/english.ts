export function translateEnglish(key: string, variables?: TranslationVariables): string {
  let message = Object.hasOwn(EN_MESSAGES, key) ? EN_MESSAGES[key] : key;
  if (message === key) {
    for (const [pattern, replacement] of DYNAMIC_MESSAGES_EN) {
      if (!pattern.test(key)) continue;
      message = key.replace(pattern, replacement);
      break;
    }
  }
  if (!variables) return message;
  return message.replace(/\{(\w+)\}/g, (_, name: string) =>
    Object.hasOwn(variables, name) ? String(variables[name]) : `{${name}}`);
}
